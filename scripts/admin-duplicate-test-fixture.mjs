import fs from 'node:fs'
import {PGlite} from '@electric-sql/pglite'
import {duplicateFunctionSql} from './admin-duplicate-capability-sql.mjs'
export const duplicateMetadata=JSON.parse(fs.readFileSync('docs/aws-phase-d/ADMIN-RDS-13-duplicate-preflight.json','utf8'))
const qi=s=>'"'+s.replaceAll('"','""')+'"'
const q=s=>"'"+s.replaceAll("'","''")+"'"
export const duplicateActor='00000000-0000-4000-8000-000000000001'
export const duplicateSource='00000000-0000-4000-8000-000000000003'
export async function createDuplicateFixture({capability=true}={}){
 const db=new PGlite()
 try{
  await db.exec(`CREATE ROLE hod_migration LOGIN NOINHERIT;CREATE ROLE hod_dev_migration LOGIN NOINHERIT;
   CREATE ROLE hod_admin_app NOLOGIN NOINHERIT;CREATE ROLE hod_app NOLOGIN;
   GRANT hod_migration TO hod_dev_migration WITH INHERIT FALSE,SET TRUE;
   GRANT USAGE,CREATE ON SCHEMA public TO hod_migration;GRANT USAGE ON SCHEMA public TO hod_admin_app,hod_app;
   CREATE SCHEMA auth;CREATE TABLE auth.users(id uuid PRIMARY KEY);GRANT USAGE ON SCHEMA auth TO hod_migration;GRANT SELECT,REFERENCES ON auth.users TO hod_migration;`)
  for(const e of duplicateMetadata.enums)await db.exec(`CREATE TYPE ${e.name} AS ENUM(${e.labels.map(q).join(',')})`)
  for(const t of duplicateMetadata.tables){
   const columns=t.columns.map(c=>`${qi(c.name)} ${c.type}${c.identity?' GENERATED BY DEFAULT AS IDENTITY':c.default?' DEFAULT '+c.default:''}${c.not_null?' NOT NULL':''}`)
   columns.push(...t.snapshot.constraints.filter(c=>!/^NOT NULL|^FOREIGN KEY/.test(c.definition)).map(c=>`CONSTRAINT ${qi(c.name)} ${c.definition}`))
   await db.exec(`CREATE TABLE ${t.name}(${columns.join(',')});ALTER TABLE ${t.name} ENABLE ROW LEVEL SECURITY;ALTER TABLE ${t.name} OWNER TO hod_migration;`)
  }
  for(const t of duplicateMetadata.tables)for(const c of t.snapshot.constraints.filter(c=>/^FOREIGN KEY/.test(c.definition))){
   const target=c.definition.match(/REFERENCES\s+([a-z_.]+)/)?.[1]
   if(target==='auth.users'||duplicateMetadata.tables.some(t=>t.name==='public.'+target||t.name===target))
    await db.exec(`ALTER TABLE ${t.name} ADD CONSTRAINT ${qi(c.name)} ${c.definition}`)
   else throw Error('Unrepresented fixture FK: '+target)
  }
  for(const t of new Map(duplicateMetadata.triggers.map(t=>[t.routine,t])).values()){
   await db.exec(t.function_definition);await db.exec(`ALTER FUNCTION public.${t.routine} OWNER TO hod_migration`)
  }
  for(const t of duplicateMetadata.triggers)await db.exec(t.definition)
  await db.exec(duplicateMetadata.legacy.definition)
  await db.exec(`ALTER FUNCTION public.duplicate_product(uuid,uuid,uuid) OWNER TO hod_migration;
   INSERT INTO auth.users(id) VALUES('${duplicateActor}');
   INSERT INTO public.profiles(id,email,role) VALUES('${duplicateActor}','fixture@example.invalid','admin');
   INSERT INTO public.admin_identities(issuer,subject,profile_id,enabled) VALUES('https://auth-uat.houseofdiams.com/realms/houseofdiams','1167a5b6-9fcb-45d1-b7d8-53e95cd49704','${duplicateActor}',true);
   INSERT INTO public.catalog_categories(id,name,slug,code,status,category_lane) VALUES('00000000-0000-4000-8000-000000000002','Fixture category','fixture-category','standard','active','standard');
   INSERT INTO public.products(id,name,slug,sku,main_category_id,stock_quantity,base_price,status,product_lane,allow_checkout)
   VALUES('${duplicateSource}','Fixture source','fixture-source','FIXTURE-SOURCE','00000000-0000-4000-8000-000000000002',7,1,'draft','standard',false);
   GRANT SELECT ON public.products TO hod_admin_app;
   CREATE POLICY installed_read ON public.products FOR SELECT TO hod_admin_app USING(true);`)
  if(capability)await db.exec('SET ROLE hod_migration;'+duplicateFunctionSql+'RESET ROLE;')
  return db
 }catch(error){await db.close();throw error}
}
