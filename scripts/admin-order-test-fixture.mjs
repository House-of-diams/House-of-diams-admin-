import fs from 'node:fs'
import {PGlite} from '@electric-sql/pglite'
import {orderFunctionSql} from './admin-order-capability-sql.mjs'
export const orderMetadata=JSON.parse(fs.readFileSync('docs/aws-phase-d/ADMIN-RDS-12-order-preflight.json','utf8'))
const qi=s=>'"'+s.replaceAll('"','""')+'"'
const q=s=>"'"+s.replaceAll("'","''")+"'"
export const fixtureActor={profileId:'00000000-0000-4000-8000-000000000001',issuer:'https://auth-uat.houseofdiams.com/realms/houseofdiams',subject:'1167a5b6-9fcb-45d1-b7d8-53e95cd49704'}
export async function createOrderFixture({capability=true}={}){
 const db=new PGlite()
 try{
  await db.exec(`CREATE ROLE hod_migration LOGIN NOINHERIT;CREATE ROLE hod_dev_migration LOGIN NOINHERIT;
   CREATE ROLE hod_admin_app NOLOGIN NOINHERIT;CREATE ROLE hod_app NOLOGIN;
   GRANT hod_migration TO hod_dev_migration WITH INHERIT FALSE,SET TRUE;
   GRANT USAGE,CREATE ON SCHEMA public TO hod_migration;GRANT USAGE ON SCHEMA public TO hod_admin_app,hod_app;`)
  for(const e of orderMetadata.enums)await db.exec(`CREATE TYPE ${e.name} AS ENUM(${e.labels.map(q).join(',')})`)
  for(const t of orderMetadata.tables){
   const columns=t.columns.map(c=>`${qi(c.name)} ${c.type}${c.identity?' GENERATED BY DEFAULT AS IDENTITY':c.default&&!c.default.includes('generate_order_number(')?' DEFAULT '+c.default:''}${c.not_null?' NOT NULL':''}`)
   columns.push(...t.snapshot.constraints.filter(c=>!/^NOT NULL|^FOREIGN KEY/.test(c.definition)).map(c=>`CONSTRAINT ${qi(c.name)} ${c.definition}`))
   await db.exec(`CREATE TABLE ${t.name}(${columns.join(',')});ALTER TABLE ${t.name} ENABLE ROW LEVEL SECURITY;ALTER TABLE ${t.name} OWNER TO hod_migration;`)
  }
  for(const t of orderMetadata.tables)for(const c of t.snapshot.constraints.filter(c=>/^FOREIGN KEY/.test(c.definition))){
   const target=c.definition.match(/REFERENCES\s+(?:public\.)?([a-z_]+)/)?.[1]
   if(orderMetadata.tables.some(t=>t.name==='public.'+target))await db.exec(`ALTER TABLE ${t.name} ADD CONSTRAINT ${qi(c.name)} ${c.definition}`)
  }
  for(const t of new Map(orderMetadata.triggers.map(t=>[t.routine,t])).values()){
   await db.exec(t.function_definition)
   await db.exec(`ALTER FUNCTION public.${t.routine} OWNER TO hod_migration`)
  }
  for(const t of orderMetadata.triggers)await db.exec(t.definition)
  await db.exec(`INSERT INTO public.profiles(id,email,role) VALUES('${fixtureActor.profileId}','fixture@example.invalid','admin');
   INSERT INTO public.admin_identities(issuer,subject,profile_id,enabled) VALUES('${fixtureActor.issuer}','${fixtureActor.subject}','${fixtureActor.profileId}',true);
   INSERT INTO public.catalog_categories(id,name,slug,code,status,category_lane) VALUES('00000000-0000-4000-8000-000000000002','Fixture category','fixture-category','standard','active','standard');
   GRANT SELECT ON public.orders,public.order_items,public.products TO hod_admin_app;
   CREATE POLICY installed_read ON public.orders FOR SELECT TO hod_admin_app USING(true);
   CREATE POLICY installed_read ON public.order_items FOR SELECT TO hod_admin_app USING(true);
   CREATE POLICY installed_read ON public.products FOR SELECT TO hod_admin_app USING(true);
   GRANT UPDATE(status,updated_at) ON public.products TO hod_admin_app;
   CREATE POLICY installed_draft ON public.products FOR UPDATE TO hod_admin_app USING(true) WITH CHECK(status::text='draft');
   CREATE POLICY installed_draft_guard ON public.products AS RESTRICTIVE FOR UPDATE TO hod_admin_app USING(true) WITH CHECK(status::text='draft');`)
  if(capability)await db.exec('SET ROLE hod_migration;'+orderFunctionSql+'RESET ROLE;')
  return db
 }catch(error){await db.close();throw error}
}
